const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(loadSavedLang);

  const setLang = useCallback((newLang) => {
    if (newLang !== 'en' && newLang !== 'fil') return;
    try {
      localStorage.setItem(LANG_KEY, newLang);
    } catch { /* ignore */ }
    setLangState(newLang);
  }, []);

  /**
   * t(key, ...args) — looks up a translation key.
   * If the value is a function, calls it with args.
   * Falls back to English, then to the raw key.
   */
  const t = useCallback((key, ...args) => {
    const dict = translations[lang] || translations.en;
    let val = dict[key];
    if (val === undefined) {
      // Fallback to English
      val = translations.en[key];
    }
    if (val === undefined) {
      // If a default fallback string was provided, use it
      if (args.length > 0 && typeof args[0] === 'string') {
        return args[0];
      }
      // Last resort: return key (prevents blank UI)
      if (import.meta.env?.DEV) {
        console.warn(`[i18n] Missing translation key: "${key}"`);
      }
      return key;
    }
    if (typeof val === 'function') return val(...args);
    return val;
  }, [lang]);

  const toggleLanguage = useCallback(() => {
    setLang(prev => (prev === 'en' ? 'fil' : 'en'));
  }, [setLang]);

  return (
    <LanguageContext.Provider value={{ lang, language: lang, setLang, setLanguage: setLang, toggleLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used within a LanguageProvider');
  return ctx;
}

export default LanguageContext;
